public class ParkingSlot {
    String slotID;
    String location;
    boolean isOccupied;
    String CurrentVehiclePlateNumber;

    public ParkingSlot(String slotID, String location, boolean isOccupied, String CurrentVehiclePlateNumber) {
        this.slotID = slotID;
        this.location = location;
        this.isOccupied = isOccupied;
        this.CurrentVehiclePlateNumber = CurrentVehiclePlateNumber;
    }

    
}
