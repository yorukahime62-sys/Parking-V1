public class Vehicle {
    String plateNumber;
    String vehicleType;
    String brand;
    String model;
    String color;
    String ownerID;

    public Vehicle(String plateNumber, String vehicleType, String brand, String model, String color, String ownerID) {
        this.plateNumber = plateNumber;
        this.vehicleType = vehicleType;
        this.brand = brand;
        this.model = model;
        this.color = color;
        this.ownerID = ownerID;
    }

    
    
}
